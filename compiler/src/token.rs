#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
    pub text: String,
    pub int: i64,
    pub scale: u32,
    pub float_val: f64,
}

impl Token {
    pub fn dummy() -> Self {
        Self {
            kind: TokenKind::Eof,
            span: Span::dummy(),
            text: String::new(),
            int: 0,
            scale: 0,
            float_val: 0.0,
        }
    }
}
